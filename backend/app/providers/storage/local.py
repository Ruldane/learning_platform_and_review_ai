"""Storage on local disk, under `settings.storage_dir`.

Two guards against leaving the folder: the key must have exactly the shape generated by `save`
(no `..`, no `\\` separator, no absolute path, no drive letter or null byte), then the resolved
path (symbolic links followed) must stay under the resolved root."""

import asyncio
import os
import re
import shutil
import tempfile
import uuid
from pathlib import Path

from app.providers.storage.base import ALLOWED_SUFFIXES, StorageKeyInvalid

_USER_ID = re.compile(r"[A-Za-z0-9-]{1,64}")
_CATEGORY = re.compile(r"[a-z_]{1,32}")
_SUFFIXES = "|".join(re.escape(s) for s in ALLOWED_SUFFIXES)
_KEY = re.compile(rf"[A-Za-z0-9-]{{1,64}}/[a-z_]{{1,32}}/[0-9a-f-]{{36}}(?:{_SUFFIXES})")


class LocalFileStorage:
    def __init__(self, root: Path) -> None:
        self._root = root

    async def save(self, user_id: str, category: str, data: bytes, suffix: str) -> str:
        if not (
            _USER_ID.fullmatch(user_id)
            and _CATEGORY.fullmatch(category)
            and suffix in ALLOWED_SUFFIXES
        ):
            raise StorageKeyInvalid()
        key = f"{user_id}/{category}/{uuid.uuid4()}{suffix}"
        await asyncio.to_thread(self._write, self._path(key, user_id), data)
        return key

    async def read(self, user_id: str, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key, user_id).read_bytes)

    async def delete(self, user_id: str, key: str) -> None:
        await asyncio.to_thread(self._path(key, user_id).unlink, missing_ok=True)

    async def list_user(self, user_id: str) -> list[str]:
        if not _USER_ID.fullmatch(user_id):
            raise StorageKeyInvalid()
        return await asyncio.to_thread(self._list_user, user_id)

    async def delete_user(self, user_id: str) -> int:
        if not _USER_ID.fullmatch(user_id):
            raise StorageKeyInvalid()
        return await asyncio.to_thread(self._delete_user, user_id)

    def _delete_user(self, user_id: str) -> int:
        """Deletes `<root>/<user_id>/`. A folder that is a link (to the outside, or to another
        account's
        folder) is refused: nothing is deleted anywhere but in `user_id`'s folder. Links **inside**
        the folder are removed without being followed."""
        root = self._root.resolve()
        folder = (root / user_id).resolve()
        if not folder.exists():
            return 0
        if folder != root / user_id:  # neither outside the root, nor another account's folder
            raise StorageKeyInvalid()
        count = len(self._list_user(user_id))
        shutil.rmtree(folder, ignore_errors=False)
        return count

    def _list_user(self, user_id: str) -> list[str]:
        """The regular files of `<root>/<user_id>/` whose key has the shape generated by `save` (the
        `.tmp-*.part` files and any intruder are ignored); a folder that is a link (to the outside
        or to another account's folder) is refused, and a linked file outside the user's folder is
        ignored."""
        root = self._root.resolve()
        folder = (root / user_id).resolve()
        if not folder.exists():
            return []
        if folder != root / user_id:  # neither outside the root, nor another account's folder
            raise StorageKeyInvalid()
        keys: list[str] = []
        for path in folder.rglob("*"):
            key = f"{user_id}/{path.relative_to(folder).as_posix()}"
            if _KEY.fullmatch(key) and path.is_file() and path.resolve().is_relative_to(folder):
                keys.append(key)
        return sorted(keys)

    def _path(self, key: str, user_id: str) -> Path:
        """The key must start with `<user_id>/` (defense in depth: another user's key, even
        well-formed,
        is refused)."""
        if not isinstance(key, str) or not _KEY.fullmatch(key):
            raise StorageKeyInvalid()
        if not _USER_ID.fullmatch(user_id) or key.split("/", 1)[0] != user_id:
            raise StorageKeyInvalid()
        root = self._root.resolve()
        path = (root / key).resolve()
        if not path.is_relative_to(root) or path == root:
            raise StorageKeyInvalid()
        return path

    @staticmethod
    def _write(path: Path, data: bytes) -> None:
        """Atomic write: a temporary file in the same folder, then `os.replace`; on failure, the
        temporary
        file is deleted and the key does not exist."""
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-", suffix=".part")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
