import { useId, type ReactNode } from "react";
import { t } from "@/shared/i18n/t";
import type { ExerciseDraft, GenerateDraft } from "../viewTypes";
import { GenerateExerciseForm } from "./GenerateExerciseForm";
import { ManualExerciseForm } from "./ManualExerciseForm";

interface ExerciseFormProps {
  creating: boolean;
  generating: boolean;
  launchMenu?: ReactNode;
  /** A success message (« Exercice ajouté. »), announced without taking focus. */
  notice: string | null;
  /** The server error, in French. */
  error: string | null;
  onCreate: (draft: ExerciseDraft) => Promise<boolean>;
  onGenerate: (draft: GenerateDraft) => void;
}

/**
 * Two ways to get an exercise: write it (statement, starter code, tests) or have it
 * generated by the agents (topic, level).
 */
export function ExerciseForm(props: ExerciseFormProps) {
  const headingId = useId();
  const { creating, generating, notice, error, onCreate, onGenerate, launchMenu } = props;
  return (
    <section aria-labelledby={headingId} className="flex flex-col gap-4">
      <h2 id={headingId} className="text-lg font-medium">
        {t("ide.form.title")}
      </h2>
      <div className="grid gap-6 lg:grid-cols-2">
        <ManualExerciseForm pending={creating} onCreate={onCreate} />
        <GenerateExerciseForm
          pending={generating}
          onGenerate={onGenerate}
          launchMenu={launchMenu}
        />
      </div>
      <p role="status" className="text-sm">
        {notice}
      </p>
      {error ? (
        <p role="alert" className="text-sm text-destructive">
          {error}
        </p>
      ) : null}
    </section>
  );
}
